<?php

use App\Services\Restaurant\Terminal\JsonTcpTerminal;

/*
| Ресторанная версия «Кассы и склада»: приложения /admin, /waiter, /cashier, /kitchen, платёжный терминал кассы
| и синхронизация с онлайн-сервером. Подробно — docs/restaurant.md.
*/
return [
    /*
    | Режим сервера.
    |  local  — сервер в ресторане: официанты, кухня и печать работают в локальной сети без интернета,
    |           раз в день отправляет заказы и продажи на онлайн-сервер и получает меню и настройки;
    |  online — облачная копия: сводная админка и отчёты, редактирование меню и настроек,
    |           принимает данные локальных серверов по sync-токену. Заказы на нём не принимаются.
    */
    'deploy_mode' => env('DEPLOY_MODE', 'local') === 'online' ? 'online' : 'local',

    'sync' => [
        // Время ежедневной синхронизации локального сервера (часовой пояс ресторана KASSA_TIMEZONE)
        'time' => env('RESTAURANT_SYNC_TIME', '03:40'),
        // Таймаут одного запроса к онлайн-серверу, секунд
        'timeout' => (int) env('RESTAURANT_SYNC_TIMEOUT', 30),
        // Сколько документов каждого вида уходит в одном запросе
        'batch' => (int) env('RESTAURANT_SYNC_BATCH', 200),
    ],

    'printer' => [
        // Ожидание соединения и отправки на сетевой принтер, секунд
        'timeout' => (float) env('RESTAURANT_PRINTER_TIMEOUT', 3),
        // После стольких неудачных попыток задание помечается «не напечатано» (повторить можно вручную)
        'max_attempts' => (int) env('RESTAURANT_PRINTER_MAX_ATTEMPTS', 10),
    ],

    /*
    | Банковский терминал кассы. Включается, адрес и порт задаются в админке (Настройки → Платёжный терминал);
    | в тестовом режиме вместо терминала работает эмулятор. Здесь — какой драйвер говорит с настоящим терминалом.
    | json — протокол-образец этого слоя (JSON по TCP, для шлюза к терминалу). Протокол конкретного терминала зависит
    | от модели и банка: для него добавляется свой драйвер (класс с интерфейсом PaymentTerminal) в drivers.
    */
    'terminal' => [
        'driver' => env('RESTAURANT_TERMINAL_DRIVER', 'json'),
        'drivers' => [
            'json' => JsonTcpTerminal::class,
        ],
        // Ожидание соединения и ответа терминала на один запрос, секунд
        'timeout' => (float) env('RESTAURANT_TERMINAL_TIMEOUT', 5),
        // Сколько ждать, пока гость оплатит на терминале, секунд; потом оплата отменяется
        'wait_seconds' => (int) env('RESTAURANT_TERMINAL_WAIT', 180),
    ],

    // Как часто экраны кухни, официанта и кассира спрашивают сервер об изменениях, секунд
    'poll_seconds' => 5,
];
